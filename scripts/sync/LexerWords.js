// The words of EFX-2 that the completions offer: for each mode of the lexer, the words it reads there
// as a token of their own, each with its token. No word is typed in: the candidates are the quoted
// words of EfxLexer.g4, and the generated lexer says where each belongs, by the token it makes of the
// word in each mode. Like the toolkit's CatalogueCompletenessTest, it finds a word's token by lexing
// the word.

// The whitespace the lexer reads between the two words of a phrase it makes one token of, such as
// OTHERWISE DISPLAY: (TAB | SPACE | EOL)+. A phrase is listed when every one of these gives its token.
const PHRASE_GAPS = [' ', '\t', '\n', ' \r\n\t '];

// Words no grammar reserves, in lower and upper case: in each mode, the tokens the lexer makes of
// them are those of a word it does not reserve there (Identifier, FreeText, StageIdentifier, ...).
const PLAIN_WORDS = ['qzxwvk', 'QZXWVK'];

export class LexerWords {
  #grammar;
  #candidates;
  // For each mode, by name, its words and phrases with their tokens.
  #modes;

  constructor(grammar) {
    this.#grammar = grammar;
    this.#candidates = grammar.quotedWords();
    this.#modes = new Map(grammar.modeNames().map((mode) => [mode, this.#wordsIn(mode)]));
  }

  /** The text of src/efx2/generated/words.js. */
  toModule(source) {
    const modes = [...this.#modes].map(([mode, words]) =>
      `  ['${mode}', new Map([\n${[...words].map(([word, token]) => `    ['${word}', '${token}'],`).join('\n')}\n  ])],`);
    return `// Generated by \`npm run sync\` from EfxLexer.g4 at ${source}. Do not edit.

// For each mode of the lexer, the words it reads as a token of their own, each with its token: a
// word, or a phrase the lexer makes one token of, written with one blank between its words.
export const modeWords = new Map([
${modes.join('\n')}
]);
`;
  }

  /** The number of words of each mode, for the sync's report. */
  toString() {
    return [...this.#modes].map(([mode, words]) => `${words.size} in ${mode}`).join(', ');
  }

  /**
   * The words a mode reads as a token of their own, with their phrases. A word is also read with a
   * blank after it, since the lexer reads DISPLAY at the start of a line as one token with the
   * whitespace that follows it.
   */
  #wordsIn(mode) {
    const tokens = new Map();
    for (const word of this.#candidates) {
      const token = [word, `${word} `].map((text) => this.#reservedToken(text, mode)).find((name) => name !== undefined);
      if (token !== undefined) {
        tokens.set(word, token);
      }
    }
    const phrases = new Map();
    for (const first of tokens.keys()) {
      for (const second of this.#candidates) {
        const [token, ...others] = PHRASE_GAPS.map((gap) => this.#reservedToken(`${first}${gap}${second}`, mode));
        if (token !== undefined && others.every((other) => other === token)) {
          phrases.set(`${first} ${second}`, token);
        }
      }
    }
    return new Map([...tokens, ...phrases]);
  }

  /** The token the lexer makes of a text in a mode, when it is one token and not that of a plain word. */
  #reservedToken(text, mode) {
    const token = this.#grammar.tokenOf(text, mode);
    const plain = PLAIN_WORDS.map((word) => this.#grammar.tokenOf(word, mode));
    return plain.includes(token) ? undefined : token;
  }
}
