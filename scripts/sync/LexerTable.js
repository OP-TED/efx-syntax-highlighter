// The table of an EFX lexer, taken from the lexer antlr-ng generates from EfxLexer.g4: its modes,
// its rules, the commands of its rules, and the network of states the rules make (ANTLR's ATN), in
// the form the editor's lexer reads (src/lexer/AntlrLexer.js). The editor's lexer is therefore
// ANTLR's lexer, rule for rule and state for state: no rule is copied by hand.
//
// A state is a list of transitions, each a list that starts with its kind:
//   [EPSILON, target]                      no character
//   [RULE, target, follow]                 into a rule (a fragment, or a token rule used as one),
//                                          which returns to follow
//   [ACTION, target, action]               a command of the rule (see actions)
//   [ATOM, target, code]                   one character, or -1 for the end of the text (EOF)
//   [SET, target, from, to, from, to, …]   a character in one of the ranges
//   [NOT_SET, target, from, to, …]         a character in none of the ranges
//   [WILDCARD, target]                     any character
// A rule ends in its stop state, which has no transitions. A lexer with what the editor's lexer does
// not read (a predicate, a non-greedy loop, a command other than type, skip, channel and the mode
// commands) stops the sync.

import { CharStream } from 'antlr4ng';

export const EPSILON = 0;
export const RULE = 1;
export const ACTION = 2;
export const ATOM = 3;
export const SET = 4;
export const NOT_SET = 5;
export const WILDCARD = 6;

// The ATN's transitions, by their classes, as the kinds above.
const KINDS = {
  EpsilonTransition: EPSILON,
  RuleTransition: RULE,
  ActionTransition: ACTION,
  AtomTransition: ATOM,
  RangeTransition: SET,
  SetTransition: SET,
  NotSetTransition: NOT_SET,
  WildcardTransition: WILDCARD,
};

export class LexerTable {
  #table;

  constructor(table) {
    this.#table = table;
  }

  /** The table of a lexer class that antlr-ng generated. */
  static of(Lexer) {
    const { atn } = new Lexer(CharStream.fromString(''));
    const nonGreedy = atn.states.find((state) => state.nonGreedy);
    if (nonGreedy !== undefined) {
      throw new Error(`The lexer has a non-greedy loop (in ${Lexer.ruleNames[nonGreedy.ruleIndex]}), which the editor's `
        + 'lexer does not read');
    }
    const typeName = (type) => Lexer.vocabulary.getSymbolicName(type);
    const states = atn.states.map((state) => state.transitions.map((transition) => LexerTable.#transition(transition)));
    return new LexerTable({
      modes: Lexer.modeNames.map((name, mode) => ({ name, start: atn.modeToStartState[mode].stateNumber })),
      rules: Lexer.ruleNames.map((name, rule) => ({
        name,
        type: atn.ruleToTokenType[rule] > 0 ? typeName(atn.ruleToTokenType[rule]) : null,
        start: atn.ruleToStartState[rule].stateNumber,
        stop: atn.ruleToStopState[rule].stateNumber,
      })),
      actions: atn.lexerActions.map((action) => LexerTable.#action(action, Lexer, typeName)),
      states,
    });
  }

  /** The text of src/efx<version>/generated/lexer.js. */
  toModule(source) {
    const { modes, rules, actions, states } = this.#table;
    const lines = (items) => items.map((item) => `    ${JSON.stringify(item)},`).join('\n');
    return `// Generated by \`npm run sync\` from EfxLexer.g4 at ${source}, by way of the lexer antlr-ng generates
// from it (scripts/sync/LexerTable.js says how the table is written). Do not edit.

export const lexerTable = {
  modes: [
${lines(modes)}
  ],
  rules: [
${lines(rules)}
  ],
  actions: [
${lines(actions)}
  ],
  states: [
${lines(states)}
  ],
};
`;
  }

  /** The size of the table, for the sync's report. */
  toString() {
    const { modes, rules, states } = this.#table;
    return `${modes.length} modes, ${rules.length} rules, ${states.length} states`;
  }

  static #transition(transition) {
    const kind = KINDS[transition.constructor.name];
    const target = transition.target.stateNumber;
    switch (kind) {
      case EPSILON:
      case WILDCARD:
        return [kind, target];
      case RULE:
        return [kind, target, transition.followState.stateNumber];
      case ACTION:
        return [kind, target, transition.actionIndex];
      case ATOM:
        return [kind, target, transition.labelValue];
      case SET:
      case NOT_SET:
        return [kind, target, ...LexerTable.#ranges(transition)];
      default:
        throw new Error(`The lexer has a transition the editor's lexer does not read: ${transition.constructor.name}`);
    }
  }

  static #ranges(transition) {
    if (transition.constructor.name === 'RangeTransition') {
      return [transition.start, transition.stop];
    }
    return [...transition.set].flatMap(({ start, stop }) => [start, stop]);
  }

  /** A command of a rule, as a list of its name and its argument, if any. */
  static #action(action, Lexer, typeName) {
    switch (action.constructor.name) {
      case 'LexerPushModeAction':
        return ['pushMode', Lexer.modeNames[action.mode]];
      case 'LexerModeAction':
        return ['mode', Lexer.modeNames[action.mode]];
      case 'LexerPopModeAction':
        return ['popMode'];
      case 'LexerTypeAction':
        return ['type', typeName(action.type)];
      case 'LexerSkipAction':
        return ['skip'];
      case 'LexerChannelAction':
        return ['channel', action.channel];
      default:
        throw new Error(`The lexer has a command the editor's lexer does not read: ${action.constructor.name}`);
    }
  }
}
